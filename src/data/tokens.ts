export function getTokensByNetwork(network: NetworkId): CustomTokenConfig[] {
  return ALL_CUSTOM_TOKENS.filter((t) => t.network === network);
}

export function getTokenByAddress(address: string, network?: NetworkId): CustomTokenConfig | undefined {
  const normalized = address.toLowerCase();
  return ALL_CUSTOM_TOKENS.find(
    (t) => t.address.toLowerCase() === normalized && (!network || t.network === network)
  );
}
